% RUN_BOOST_LAB Edit boost-parameters.json or use a web-exported parameter file.
folder=fileparts(mfilename('fullpath'));rootFolder=fileparts(folder);addpath(folder);
p=jsondecode(fileread(fullfile(rootFolder,'boost-parameters.json')));
out=fullfile(rootFolder,'results','boost');if ~isfolder(out),mkdir(out);end
r=boost_model(p);f=boost_frequency(p);writetable(r.rows,fullfile(out,'waveforms.csv'));writetable(f,fullfile(out,'frequency.csv'));
fid=fopen(fullfile(out,'metrics.json'),'w','n','UTF-8');assert(fid~=-1);fprintf(fid,'%s',jsonencode(r.metrics,PrettyPrint=true));fclose(fid);
copyfile(fullfile(rootFolder,'boost-parameters.json'),fullfile(out,'parameters.json'));
ink=[.12,.24,.21];teal=[.137,.42,.345];orange=[.73,.4,.2];
fig=figure('Visible','off','Color',[1,1,.98],'Position',[100,100,1100,850]);
tiledlayout(fig,3,1,'Padding','compact');
for j=1:3
    ax=nexttile;cols={'v_V','iL_A','iD_A'};labels={'Output voltage (V)','Inductor/input current (A)','Diode current (A)'};
    plot(ax,r.rows.t_s*1e6,r.rows.(cols{j}),'Color',teal,'LineWidth',1.5);grid(ax,'on');xlabel(ax,'Time (us)');ylabel(ax,labels{j});
end
style(fig,ink);exportgraphics(fig,fullfile(out,'waveforms.png'),'Resolution',150,'BackgroundColor',[1,1,.98]);close(fig);
fig=figure('Visible','off','Color',[1,1,.98],'Position',[100,100,1100,700]);tiledlayout(fig,2,1,'Padding','compact');
ax=nexttile;semilogx(ax,f.f_Hz,f.gain_dB,'Color',teal);grid(ax,'on');ylabel(ax,'Gain (dB re 1 V/duty)');xlabel(ax,'Frequency (Hz)');title(ax,'CCM average model only: RHP zero');xline(ax,p.fs/10,'--','fs/10','Color',orange);
ax=nexttile;semilogx(ax,f.f_Hz,f.phase_deg,'Color',teal);grid(ax,'on');ylabel(ax,'Phase (deg)');xlabel(ax,'Frequency (Hz)');
style(fig,ink);exportgraphics(fig,fullfile(out,'frequency.png'),'Resolution',150,'BackgroundColor',[1,1,.98]);close(fig);
% Remove only outdated step artifacts generated by this entry point if the
% edited work point no longer qualifies for the CCM positive-step demo.
stepFiles={'step.csv','step-metrics.json','step.png'};
if strcmp(r.metrics.mode,'CCM') && p.D+.02<=.7+1e-12
    try
        s=boost_step(p);writetable(s.rows,fullfile(out,'step.csv'));
        if ~s.metrics.ccmThroughout
            warning('Boost:TransientDCM','Current touches zero during the transient; the CCM average curve is reference only.');
        end
        fid=fopen(fullfile(out,'step-metrics.json'),'w','n','UTF-8');assert(fid~=-1);fprintf(fid,'%s',jsonencode(s.metrics,PrettyPrint=true));fclose(fid);
        fig=figure('Visible','off','Color',[1,1,.98],'Position',[100,100,1100,750]);tiledlayout(fig,2,1,'Padding','compact');
        ax=nexttile;[tg,vg]=gap(s.rows.t_s*1000,s.rows.v_sw_mean_V);plot(ax,tg,vg,'Color',teal,'LineWidth',1.3);hold(ax,'on');[tg,vg]=gap(s.rows.t_s*1000,s.rows.v_avg_V);plot(ax,tg,vg,'--','Color',orange,'LineWidth',1.2);xline(ax,0,':','t=0','HandleVisibility','off','Color',ink);grid(ax,'on');xlabel(ax,'Time (ms)');ylabel(ax,'Output (V)');if s.metrics.ccmThroughout,title(ax,'Duty +0.02 at t=0; actual switching cycle means vs average ODE');else,title(ax,'Transient DCM: CCM average curve is reference only');end;legend(ax,'Switching cycle means','CCM average','Location','southoutside','Orientation','horizontal');
        early=s.rows.t_s<=100e-6 & s.rows.t_s>=-100e-6;ax=nexttile;
        [tg,vg]=gap(s.rows.t_s(early)*1e6,(s.rows.v_sw_mean_V(early)-s.metrics.oldV)*1000);plot(ax,tg,vg,'o-','Color',teal,'LineWidth',1.3);hold(ax,'on');[tg,vg]=gap(s.rows.t_s(early)*1e6,(s.rows.v_avg_V(early)-r.metrics.Vccm)*1000);plot(ax,tg,vg,'s--','Color',orange,'LineWidth',1.2);yline(ax,0,':','HandleVisibility','off','Color',ink);xline(ax,0,':','t=0','HandleVisibility','off','Color',ink);grid(ax,'on');xlabel(ax,'Time (us)');ylabel(ax,'Change from own pre-step mean (mV)');title(ax,'First 100 us after step: inverse response enlarged');legend(ax,'Switching cycle means','CCM average','Location','southoutside','Orientation','horizontal');
        style(fig,ink);exportgraphics(fig,fullfile(out,'step.png'),'Resolution',150,'BackgroundColor',[1,1,.98]);close(fig);
    catch errorInfo
        if ~strcmp(errorInfo.identifier,'Boost:StepCCM'),rethrow(errorInfo);end
        for j=1:numel(stepFiles),file=fullfile(out,stepFiles{j});if isfile(file),delete(file);end;end
        warning('Boost:StepSkipped','Step skipped: final state is not CCM.');
    end
else
    for j=1:numel(stepFiles),file=fullfile(out,stepFiles{j});if isfile(file),delete(file);end;end
    disp('CCM step demo skipped for current parameters; waveform exports remain valid.');
end
verify_boost(rootFolder);
fprintf('Boost mode=%s, V=%.9f V, Iin=%.9f A\n',r.metrics.mode,r.metrics.Vmean,r.metrics.IinMean);
function style(fig,ink)
axesList=findobj(fig,'Type','axes');set(axesList,'Color',[1,1,.98],'XColor',ink,'YColor',ink,'GridColor',[.6,.65,.6],'GridAlpha',.4,'FontSize',11);
for j=1:numel(axesList),ax=axesList(j);ax.Title.Color=ink;ax.XLabel.Color=ink;ax.YLabel.Color=ink;end
legends=findobj(fig,'Type','legend');set(legends,'Color',[1,1,.98],'TextColor',ink);
end
function [tout,yout]=gap(t,y)
% Cycle means are timestamped at cycle midpoints. Do not connect the final
% pre-step point to the first post-step point across t=0.
tout=[t(t<0);0;t(t>0)];yout=[y(t<0);NaN;y(t>0)];
end
